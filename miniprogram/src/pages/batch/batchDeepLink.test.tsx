import { renderToStaticMarkup } from 'react-dom/server';
import { beforeEach, expect, test, vi } from 'vitest';
const fixture = vi.hoisted(() => ({ params: {} as Record<string, string>, show: undefined as undefined | (() => void), paths: [] as string[] }));
vi.mock('@tarojs/components', () => ({ View: 'div', Text: 'span', Button: 'button', Input: 'input', Picker: 'select', Textarea: 'textarea', Image: 'img', Video: 'video' }));
vi.mock('@tarojs/taro', () => ({ useRouter: () => ({ params: fixture.params }), useDidHide: () => {}, useDidShow: (callback: () => void) => { fixture.show = callback; }, default: { getCurrentInstance: () => ({ router: { params: fixture.params } }), getStorageSync: () => '', env: {}, getFileSystemManager: () => ({}) } }));
vi.mock('./useAutomationPolling', () => ({ useAutomationPolling: () => {} }));
vi.mock('../../theme', () => ({ ThemedPage: 'div' }));
vi.mock('../../components/BrandHeader', () => ({ default: () => null }));
vi.mock('../../components/AppIcon', () => ({ default: () => null }));
vi.mock('../../services/batchLocalAccess', () => ({ batchLocalRequest: async (path: string) => { fixture.paths.push(path); if (path.endsWith('/batches')) return { batches: [{ id: 'first' }, { id: 'target/a' }] }; if (path.includes('/batches/')) return { batch: { id: 'target/a', books: [] } }; return {}; } }));
import BatchPage from './index';
beforeEach(() => { fixture.paths = []; fixture.params = {}; fixture.show = undefined; });
test('batch task deep link opens project mode and first show reads its exact encoded batch', async () => {
  fixture.params = { batchId: 'target/a' };
  const html = renderToStaticMarkup(<BatchPage />);
  expect(html).toContain('正在读取作品');
  fixture.show?.();
  await vi.waitFor(() => expect(fixture.paths).toContain('/api/batch-factory/v12/batches/target%2Fa'));
  expect(fixture.paths).not.toContain('/api/batch-factory/v12/batches/first');
});
